// Generate realistic 12km (coarse 8x8) vs 5km (downscaled 16x16) grid matrices
function generateGrids(): { coarseGrid: DownscaledForecast['coarseGrid']; downscaledGrid: DownscaledForecast['downscaledGrid'] } {
  const coarseGrid = [];
  const downscaledGrid = [];

  // Coarse 8x8 grid (smoothed peak at ~195mm)
  for (let y = 0; y < 8; y++) {
    for (let x = 0; x < 8; x++) {
      const distFromCenter = Math.sqrt(Math.pow(x - 3.5, 2) + Math.pow(y - 3.5, 2));
      const intensity = Math.max(10, Math.round(100 * Math.exp(-distFromCenter / 2.2)));
      const rainfallMm = Math.round(30 + (intensity / 100) * 165);
      coarseGrid.push({
        x,
        y,
        intensity,
        rainfallMm,
        isPeak: rainfallMm > 185,
      });
    }
  }

  // Downscaled 16x16 grid (peak-preserved, sharp convective cores up to 294mm)
  for (let y = 0; y < 16; y++) {
    for (let x = 0; x < 16; x++) {
      // Create two sharp localized convective cells + orographic ridge effect
      const d1 = Math.sqrt(Math.pow(x - 7, 2) + Math.pow(y - 8, 2));
      const d2 = Math.sqrt(Math.pow(x - 11, 2) + Math.pow(y - 5, 2));
      const cell1 = Math.exp(-d1 / 1.8) * 100;
      const cell2 = Math.exp(-d2 / 1.4) * 85;
      const localNoise = Math.sin(x * 1.5) * Math.cos(y * 1.5) * 6;
      const intensity = Math.min(100, Math.max(8, Math.round(Math.max(cell1, cell2) + localNoise)));
      const rainfallMm = Math.round(25 + (intensity / 100) * 269);
      downscaledGrid.push({
        x,
        y,
        intensity,
        rainfallMm,
        isPeak: rainfallMm > 260,
      });
    }
  }

  return { coarseGrid, downscaledGrid };
}

